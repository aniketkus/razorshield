"""
RazorShield – Chargeback Evidence Responder
Scores chargeback risk and auto-generates structured dispute response documents.
"""
import joblib
import pandas as pd
from pathlib import Path
from pydantic import BaseModel, Field
from datetime import datetime
from typing import Optional

MODELS_DIR = Path(__file__).parent.parent / "saved_models"

_preprocessor = None
_classifier   = None


def _load_models():
    global _preprocessor, _classifier
    if _preprocessor is None:
        _preprocessor = joblib.load(MODELS_DIR / "chargeback_preprocessor.pkl")
        _classifier   = joblib.load(MODELS_DIR / "chargeback_classifier.pkl")


class ChargebackInput(BaseModel):
    txn_id:              str
    customer_id:         str
    merchant_id:         str
    merchant_name:       str
    category:            str
    amount:              float
    payment_method:      str
    state:               str
    device_type:         str
    browser:             str
    hour:                int   = Field(..., ge=0, le=23)
    day_of_week:         int   = Field(..., ge=0, le=6)
    txn_velocity_24h:    int   = Field(1, ge=1)
    amount_velocity_24h: float = Field(0.0)
    device_fp_count:     int   = Field(1, ge=1)
    delivery_confirmed:  bool  = False
    ip_address:          Optional[str] = None
    shipping_address:    Optional[str] = None
    dispute_reason:      str   = Field("unknown",
                                       description="not_received | unauthorized | duplicate | unknown")
    txn_timestamp:       Optional[str] = None


class ChargebackOutput(BaseModel):
    txn_id:             str
    chargeback_risk:    float
    win_probability:    float   # probability merchant WINS the dispute
    recommended_action: str
    evidence_document:  str     # full text evidence response
    evidence_points:    list[str]


_REASON_DEFENSE: dict[str, list[str]] = {
    "not_received": [
        "Tracking number and delivery confirmation attached",
        "Delivery partner GPS log shows successful delivery",
        "Customer OTP-based delivery confirmation received",
    ],
    "unauthorized": [
        "Transaction authenticated via 3D-Secure / OTP",
        "Device fingerprint matches customer registered device",
        "IP address geolocates to customer registered state",
        "No prior dispute history on this customer account",
    ],
    "duplicate": [
        "System logs show single successful payment capture",
        "No duplicate charge found in reconciliation report",
        "Bank settlement report attached showing single debit",
    ],
    "unknown": [
        "Transaction completed with successful payment gateway acknowledgment",
        "Customer account verified at time of purchase",
    ],
}


def _generate_evidence_document(inp: ChargebackInput, score: float,
                                 win_prob: float, points: list[str]) -> str:
    now      = datetime.utcnow().strftime("%d %B %Y %H:%M UTC")
    day_name = ["Monday","Tuesday","Wednesday","Thursday","Friday","Saturday","Sunday"][inp.day_of_week]
    verdict  = (
        "Strong case to contest" if win_prob > 0.60
        else "Moderate case — gather additional evidence" if win_prob > 0.40
        else "Consider accepting chargeback"
    )
    delivery_line = "  [+] Delivery confirmed by logistics partner" if inp.delivery_confirmed else ""
    evidence_list = "\n".join(f"  [{i+1}] {p}" for i, p in enumerate(points))
    bullet_list   = "\n".join(f"* {p}" for p in points)

    return f"""
================================================
  CHARGEBACK DISPUTE RESPONSE DOCUMENT
  Generated by RazorShield AI -- {now}
================================================

MERCHANT:       {inp.merchant_name} ({inp.merchant_id})
TRANSACTION ID: {inp.txn_id}
AMOUNT:         Rs.{inp.amount:,.2f}
CATEGORY:       {inp.category.title()}
PAYMENT METHOD: {inp.payment_method.upper()}
DISPUTE REASON: {inp.dispute_reason.replace("_", " ").title()}

------------------------------------------------
TRANSACTION DETAILS
------------------------------------------------
Date/Time : {day_name}, {inp.txn_timestamp or "on file"}
Customer  : {inp.customer_id}
State     : {inp.state}
Device    : {inp.device_type.title()} / {inp.browser.title()}
IP Address: {inp.ip_address or "on file with gateway"}

------------------------------------------------
AI RISK ASSESSMENT
------------------------------------------------
Chargeback Risk Score   : {score:.1%}
Win Probability         : {win_prob:.1%}
Verdict                 : {verdict}

------------------------------------------------
EVIDENCE SUMMARY
------------------------------------------------
{evidence_list}
{delivery_line}

------------------------------------------------
RECOMMENDED RESPONSE TO BANK / CARD NETWORK
------------------------------------------------
Dear Dispute Resolution Team,

We are writing in response to the chargeback filed against
Transaction ID {inp.txn_id} for Rs.{inp.amount:,.2f}.

This transaction was completed legitimately by the cardholder
on {inp.txn_timestamp or "the recorded date"} via {inp.payment_method.upper()}.
The payment was authenticated through our PCI-DSS compliant
gateway (Razorpay) with full 3DS/OTP verification.

{bullet_list}

We respectfully request that this chargeback be reversed.
All supporting documentation is attached.

Sincerely,
{inp.merchant_name}
[Powered by RazorShield AI Risk Manager]
================================================
""".strip()


def respond_chargeback(inp: ChargebackInput) -> ChargebackOutput:
    _load_models()
    row = pd.DataFrame([{
        "payment_method":      inp.payment_method,
        "state":               inp.state,
        "device_type":         inp.device_type,
        "browser":             inp.browser,
        "category":            inp.category,
        "amount":              inp.amount,
        "hour":                inp.hour,
        "day_of_week":         inp.day_of_week,
        "txn_velocity_24h":    inp.txn_velocity_24h,
        "amount_velocity_24h": inp.amount_velocity_24h,
        "device_fp_count":     inp.device_fp_count,
    }])

    X     = _preprocessor.transform(row)
    score = float(_classifier.predict_proba(X)[0, 1])

    # Win probability = inverse of risk + bonuses for strong evidence
    win_base = 1.0 - score
    if inp.delivery_confirmed:
        win_base = min(0.95, win_base + 0.15)
    if inp.dispute_reason == "unauthorized" and inp.device_fp_count == 1:
        win_base = min(0.95, win_base + 0.10)
    win_prob = round(win_base, 4)

    # Build evidence points
    base_points = _REASON_DEFENSE.get(inp.dispute_reason, _REASON_DEFENSE["unknown"])
    extra = []
    if inp.txn_velocity_24h == 1:
        extra.append("No suspicious velocity — single transaction from this customer")
    if inp.amount <= 10_000:
        extra.append("Transaction amount within normal range for this category")
    evidence_points = base_points + extra

    action = (
        "Contest chargeback — strong evidence available"
        if win_prob > 0.60 else
        "Contest with supplementary evidence"
        if win_prob > 0.40 else
        "Accept chargeback — contestation unlikely to succeed"
    )

    return ChargebackOutput(
        txn_id             = inp.txn_id,
        chargeback_risk    = round(score, 4),
        win_probability    = win_prob,
        recommended_action = action,
        evidence_document  = _generate_evidence_document(inp, score, win_prob, evidence_points),
        evidence_points    = evidence_points,
    )
